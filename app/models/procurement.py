from datetime import date, datetime
from . import db

class StockRequirement(db.Model):
    __tablename__ = 'stock_requirements'
    id = db.Column(db.Integer, primary_key=True)
    request_number = db.Column(db.String(50), unique=True, nullable=False, index=True)
    requested_by = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=False)
    status = db.Column(db.String(30), nullable=False, default='PENDING', index=True)
    reviewed_by = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=True)
    reviewed_at = db.Column(db.DateTime, nullable=True)
    rejection_reason = db.Column(db.Text, nullable=True)
    notes = db.Column(db.Text, nullable=True)
    created_at = db.Column(db.DateTime, nullable=False, default=datetime.utcnow)
    updated_at = db.Column(db.DateTime, nullable=False, default=datetime.utcnow, onupdate=datetime.utcnow)
    items = db.relationship('StockRequirementItem', backref='requirement', lazy='dynamic', cascade='all, delete-orphan')
    requester = db.relationship('User', foreign_keys=[requested_by], backref='stock_requirements')
    reviewer = db.relationship('User', foreign_keys=[reviewed_by])

class StockRequirementItem(db.Model):
    __tablename__ = 'stock_requirement_items'
    id = db.Column(db.Integer, primary_key=True)
    stock_requirement_id = db.Column(db.Integer, db.ForeignKey('stock_requirements.id', ondelete='CASCADE'), nullable=False)
    product_id = db.Column(db.Integer, db.ForeignKey('products.id'), nullable=False)
    original_quantity = db.Column(db.Integer, nullable=False)
    approved_quantity = db.Column(db.Integer, nullable=True)
    quantity_adjustment_reason = db.Column(db.Text, nullable=True)
    unit = db.Column(db.String(20), nullable=True)
    created_at = db.Column(db.DateTime, nullable=False, default=datetime.utcnow)
    product = db.relationship('Product')
    __table_args__ = (db.UniqueConstraint('stock_requirement_id', 'product_id', name='uq_requirement_product'),)

class SupplierInvoice(db.Model):
    __tablename__ = 'supplier_invoices'
    id = db.Column(db.Integer, primary_key=True)
    invoice_number = db.Column(db.String(50), nullable=False, index=True)
    supplier_id = db.Column(db.Integer, db.ForeignKey('suppliers.id'), nullable=False)
    purchase_id = db.Column(db.Integer, db.ForeignKey('purchases.id'), nullable=True)
    invoice_date = db.Column(db.Date, nullable=False, default=date.today)
    due_date = db.Column(db.Date, nullable=True)
    total_amount = db.Column(db.Numeric(12, 2), nullable=False)
    status = db.Column(db.String(20), nullable=False, default='PENDING', index=True)
    created_by = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=False)
    created_at = db.Column(db.DateTime, nullable=False, default=datetime.utcnow)
    purchase = db.relationship('Purchase', backref='supplier_invoices')
    supplier = db.relationship('Supplier', backref='invoices')
    __table_args__ = (db.UniqueConstraint('supplier_id', 'invoice_number', name='uq_supplier_invoice_number'),)

class SupplierPayment(db.Model):
    __tablename__ = 'supplier_payments'
    id = db.Column(db.Integer, primary_key=True)
    payment_number = db.Column(db.String(50), nullable=False, unique=True, index=True)
    supplier_id = db.Column(db.Integer, db.ForeignKey('suppliers.id'), nullable=False)
    purchase_id = db.Column(db.Integer, db.ForeignKey('purchases.id'), nullable=True)
    supplier_invoice_id = db.Column(db.Integer, db.ForeignKey('supplier_invoices.id'), nullable=True)
    amount = db.Column(db.Numeric(12, 2), nullable=False)
    payment_date = db.Column(db.Date, nullable=False, default=date.today)
    payment_method = db.Column(db.String(30), nullable=False, default='BANK')
    reference_number = db.Column(db.String(100), nullable=True, index=True)
    recorded_by = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=False)
    notes = db.Column(db.Text, nullable=True)
    created_at = db.Column(db.DateTime, nullable=False, default=datetime.utcnow)
    supplier = db.relationship('Supplier', backref='payments')
    purchase = db.relationship('Purchase', backref='supplier_payments')
    invoice = db.relationship('SupplierInvoice', backref='payments')
    recorder = db.relationship('User', foreign_keys=[recorded_by])

class GoodsReceivingReport(db.Model):
    __tablename__ = 'goods_receiving_reports'
    id = db.Column(db.Integer, primary_key=True)
    report_number = db.Column(db.String(50), nullable=False, unique=True, index=True)
    purchase_id = db.Column(db.Integer, db.ForeignKey('purchases.id'), nullable=False)
    submitted_by = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=False)
    submitted_at = db.Column(db.DateTime, nullable=False, default=datetime.utcnow)
    status = db.Column(db.String(30), nullable=False, default='SUBMITTED', index=True)
    reviewed_by = db.Column(db.Integer, db.ForeignKey('users.id'), nullable=True)
    reviewed_at = db.Column(db.DateTime, nullable=True)
    supplier_invoice_id = db.Column(db.Integer, db.ForeignKey('supplier_invoices.id'), nullable=True)
    invoice_number = db.Column(db.String(50), nullable=True)
    delivery_reference = db.Column(db.String(100), nullable=True)
    delivery_date = db.Column(db.Date, nullable=False, default=date.today)
    notes = db.Column(db.Text, nullable=True)
    inventory_applied = db.Column(db.Boolean, nullable=False, default=False)
    inventory_applied_at = db.Column(db.DateTime, nullable=True)
    created_at = db.Column(db.DateTime, nullable=False, default=datetime.utcnow)
    purchase = db.relationship('Purchase', backref='receiving_reports')
    submitter = db.relationship('User', foreign_keys=[submitted_by], backref='submitted_receiving_reports')
    reviewer = db.relationship('User', foreign_keys=[reviewed_by])
    supplier_invoice = db.relationship('SupplierInvoice', backref='receiving_reports')
    items = db.relationship('GoodsReceivingItem', backref='receiving_report', lazy='dynamic', cascade='all, delete-orphan')

